"""Write coeffs.h for bench.cpp: complex tableaux from ../../data/tableaux.json, real
methods from rk_tableaux.json (via tableaux.real_methods), all in double precision.
nreal = number of leading stages whose rows are real (evaluated in real arithmetic).
    python gen_coeffs.py METHOD[,METHOD...]
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import mpmath as mp
from tableaux import load_refined, real_methods

NS = 16
mp.mp.dps = 30
TT = load_refined()
TT.update(real_methods())
METHODS = sys.argv[1].split(",")
lines = ["// generated by gen_coeffs.py -- do not edit", "#pragma once", "#include <complex>",
         f"static const int NS = {NS};",
         "struct Tab { const char* name; int s; bool cplx; bool fsal; int nreal; double are[NS][NS]; double aim[NS][NS];"
         " double bre[NS]; double bim[NS]; double cre[NS]; double cim[NS]; };",
         f"static const int NMETH = {len(METHODS)};", "static const Tab TABS[NMETH] = {"]
for nm in METHODS:
    T = TT[nm]
    m, p, b = T.levels[0]
    s = 1 + max(i for i, v in enumerate(b) if v != 0)   # stages used by the propagated formula
    b = b[:s]
    are = [[float(mp.re(T.A[i][j])) if (i < s and j < i) else 0.0 for j in range(NS)] for i in range(NS)]
    # imaginary parts below 1e-30 are the round-off of the 60-digit refinement of real entries
    aim = [[float(mp.im(T.A[i][j])) if (i < s and j < i and abs(mp.im(T.A[i][j])) > 1e-30) else 0.0 for j in range(NS)] for i in range(NS)]
    bre = [float(mp.re(v)) for v in b] + [0.0] * (NS - s)
    bim = [float(mp.im(v)) for v in b] + [0.0] * (NS - s)
    cre = [sum(are[i][:i]) for i in range(NS)]
    cim = [sum(aim[i][:i]) for i in range(NS)]
    nreal = 1
    while nreal < s and all(aim[nreal][j] == 0.0 for j in range(nreal)):
        nreal += 1
    fsal = (not T.projected) and all(abs(are[s - 1][j] - bre[j]) < 1e-15 for j in range(s - 1)) and abs(bre[s - 1]) < 1e-15
    f = lambda M: "{" + ",".join("{" + ",".join(repr(x) for x in row) + "}" for row in M) + "}"
    v = lambda x: "{" + ",".join(repr(y) for y in x) + "}"
    lines.append(f'  {{"{nm}", {s}, {"true" if T.projected else "false"}, {"true" if fsal else "false"}, {nreal}, '
                 f'{f(are)}, {f(aim)}, {v(bre)}, {v(bim)}, {v(cre)}, {v(cim)}}},')
    print(f"{nm:14s} s={s:2d} projected={T.projected} nreal={nreal} fsal={fsal}")
lines.append("};")
open(os.path.join(HERE, "coeffs.h"), "w").write("\n".join(lines) + "\n")
print("wrote coeffs.h")
